/* Data correspinding to the invariant mass distributions
   for the Bs into J/Psi proton antiproton decay:

   (i) m12_data is the central point of the bin in the histogram
       for the m12 invariant mass distribution.

   (ii) Owing to the fact that the proton and antiproton have
        identical masses, there is no independent m23_data
	array (it would be identical to m12_data).

   (iii) events_data is the array containing the bin counts
         for the m12 mass distribution.

   (iv) err_data is the error for the bin counts (which actually
        is just the square root of the counts in events_data).

   (v) background_data is the noise (i.e. the background).

   (vi-viii) same, but with bar: events_bar_data, err_bar_data,
             background_bar_data, which are for m23 (J/Psi antiproton,
	     or \bar{p} in LaTeX, hence the name.

   (ix) z_data is the central point for cos(\theta_p) in the histogram

   (x) events_z_data are the bin counts for the cos(\theta_p) distro

   (xi) background_z_data the noise

   (xii) however, I did not include err_z_data, because it would
         simply be the square root of events_z_data (while for
	 events_data and events_bar_data the errors were
	 explicitly included because of how the programs
	 were originally written).
 */

  
